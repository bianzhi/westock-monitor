def get_concept_sectors() -> Dict[str, str]:
    """获取概念板块代码→名称映射，优先从缓存读取。"""
    if CONCEPT_CACHE.exists():
        try:
            with open(CONCEPT_CACHE, "r", encoding="utf-8") as f:
                cached = json.load(f)
                if isinstance(cached, dict) and cached:
                    return cached
        except (json.JSONDecodeError, OSError):
            pass
    return dict(VERIFIED_CONCEPTS)


def save_concept_sectors(sectors: Dict[str, str]) -> None:
    """保存概念板块清单到缓存文件。"""
    try:
        with open(CONCEPT_CACHE, "w", encoding="utf-8") as f:
            json.dump(sectors, f, ensure_ascii=False, indent=2)
        logger.info("concept_sectors: saved %d sectors to cache", len(sectors))
    except OSError as e:
        logger.warning("concept_sectors: save failed: %s", e)


def add_concept(code: str, name: str) -> bool:
    """手动添加一个概念板块到缓存。

    Args:
        code: 板块代码（pt02xxxxxx）
        name: 板块名称

    Returns:
        True 表示新增，False 表示已存在
    """
    sectors = get_concept_sectors()
    if code in sectors:
        return False
    sectors[code] = name
    save_concept_sectors(sectors)
    return True


def get_default_codes() -> List[str]:
    """获取概念板块代码列表。"""
    return list(get_concept_sectors().keys())


def get_default_name(code: str) -> str:
    """根据代码获取概念板块名称。"""
    return get_concept_sectors().get(code, code)


def search_and_merge_concepts(keyword: str, dry_run: bool = False) -> Dict[str, Any]:
    """从 westock search --type sector 反查关键词，把概念板块补进白名单。

    用于"概念板块可发现"：用户搜不到的概念板块，通过此函数从接口
    反查补全到缓存清单，下次就在宽表里出现。

    Args:
        keyword: 搜索关键词，如 "ChatGPT" / "军工"
        dry_run: True 时不写缓存，只返回"将会新增"的候选（供确认展示）

    Returns:
        {"added": [{code, name}, ...], "total_before": N, "total_after": M}
    """
    from westock import search_sector
    results = search_sector(keyword, raw=True) or []
    before = len(get_concept_sectors())
    added: List[Dict[str, str]] = []
    for r in results:
        # 仅接受分类含"概念"的条目，避免误把二级行业混进来
        if "概念" not in (r.get("分类") or ""):
            continue
        code = r.get("code") or r.get("SecuCode")
        name = r.get("name") or r.get("Name") or ""
        if code and name:
            if dry_run:
                # dry-run：不写库，仅当该码不在现有清单时算作候选
                if code not in get_concept_sectors():
                    added.append({"code": code, "name": name})
            else:
                if add_concept(code, name):
                    added.append({"code": code, "name": name})
    return {
        "added": added,
        "total_before": before,
        "total_after": len(get_concept_sectors()) if not dry_run else before + len(added),
    }
