def _sw_to_pt(sw_code: str) -> str:
    """申万二级代码 → westock pt 代码。

    映射规则（实测 116/124 完全匹配）：
        pt + "018" + 申万二级代码去掉首位 "8" 的部分
        即 pt + "018" + sw_code[1:]
    示例：
        申万 801081 (半导体) → pt01801081
        申万 801016 (种植业) → pt01801016
        申万 801161 (电力)   → pt01801161

    Args:
        sw_code: 申万二级 6 位代码，如 "801081"

    Returns:
        westock pt 代码，如 "pt01801081"
    """
    # 801081 → sw_code[1:] = "01081" → "pt" + "018" + "01081" = "pt01801081"
    return "pt" + "018" + sw_code[1:]


def _pt_to_sw(pt_code: str) -> str:
    """westock pt 代码 → 申万二级代码（反向映射）。

    Args:
        pt_code: westock pt 代码，如 "pt01801081"

    Returns:
        申万二级 6 位代码，如 "801081"
    """
    # pt01801081 → 去 pt = "01801081"
    # 去 "018" 前缀 = "01081"
    # 加回首位 "8" = "801081"
    num = pt_code[2:]           # "01801081"
    body = num[3:]              # "01081" (去掉 018 前缀)
    return "8" + body           # "801081"


